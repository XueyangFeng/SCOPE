from __future__ import annotations

from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from scope.common.datasets import TaskRecord
from scope.common.io import append_jsonl, save_json
from scope.common.prompts import PromptBundle
from scope.common.store import MemoryStoreLayout


def build_memory_layout(memory_root: str | Path) -> MemoryStoreLayout:
    return MemoryStoreLayout(Path(memory_root))


def write_stub_prefix_memory(
    layout: MemoryStoreLayout,
    task: TaskRecord,
    *,
    dataset: str,
    prompts: PromptBundle,
) -> Path:
    path = layout.prefix_memory_path(task.task_id)
    save_json(
        path,
        {
            "schema_version": 1,
            "dataset": dataset,
            "task_id": task.task_id,
            "source_path": str(task.source_path) if task.source_path else None,
            "source_score": task.score,
            "source_success": task.success,
            "source_reason": task.reason,
            "prompt_template": str(prompts.generator),
            "update_prompt_template": str(prompts.update),
            "status": "stub_generated_without_llm",
            "memories": [
                {
                    "id": "stub-0",
                    "text": "Stub memory generated by the Scope prototype. Replace this with LLM output using the recorded prompt_template.",
                    "created_at": datetime.now(timezone.utc).isoformat(),
                }
            ],
        },
    )
    return path


def write_stub_selected_anchor(
    layout: MemoryStoreLayout,
    task: TaskRecord,
    *,
    dataset: str,
    prompts: PromptBundle,
) -> Path:
    path = layout.selected_anchor_path(task.task_id)
    append_jsonl(
        path,
        {
            "schema_version": 1,
            "dataset": dataset,
            "task_id": task.task_id,
            "memory_id": "stub-0",
            "prompt_template": str(prompts.selector),
            "status": "stub_selected_without_llm",
            "reason": "Prototype selector chooses the first available stub memory.",
        },
    )
    return path


